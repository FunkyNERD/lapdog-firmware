#!/usr/bin/env python3
"""Generates src/touch/touch_art.h: the touch timer's LapDog artwork as LVGL
RGB565A8 image data (RGB565 plane, then an 8-bit alpha plane), kept in flash.

- dog:      the mark without its signal arcs, for the boot splash (which draws
            the arcs itself, so they can bark);
- wordmark: "LAPDOG", for the boot splash;
- lockup:   mark + wordmark, arcs included, for the idle screen's top bar.

Reads the PNGs from lapdog-web's brand kit, so the timer's logo can't drift from it
(as lapdog-lcd's tools/gen-splash.py does):

    python3 tools/gen-touch-art.py ../web/brand

Needs Pillow.
"""
import os
import sys

from PIL import Image

BRAND = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "..", "web", "brand")
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "touch", "touch_art.h")

# Mark geometry, in gen.py's 140x100 design units. The PNG is MARK_BOX scaled to 512 wide.
MARK_X, MARK_Y, MARK_W, MARK_H = 27, 3, 97, 89
ARCS_FROM = 102.5  # everything right of the dog's nose is the arcs
SCALE = 1.1        # px per design unit on the splash

# Lockup: mark (1.6 x cap height) + gap + wordmark, 565.3 x 112 units, 70-unit cap height.
LOCKUP_W, LOCKUP_H, WORD_X, WORD_CAP = 565.3, 112.0, 153.6, 70.0
WORD_H = 34    # px cap height of the splash's wordmark
LOCKUP_PX = 30  # px height of the top bar's lockup


def resize(im, size):
    # Resample with premultiplied alpha, so transparent edges don't bleed dark fringes.
    return im.convert("RGBa").resize(size, Image.LANCZOS).convert("RGBA")


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def image(name, im):
    w, h = im.size
    px = list(im.getdata())
    data = []
    for r, g, b, a in px:
        c = rgb565(r, g, b) if a else 0
        data += [c & 0xFF, c >> 8]  # little-endian, as LVGL holds RGB565
    data += [a for _, _, _, a in px]
    rows = [", ".join(f"0x{v:02X}" for v in data[i:i + 24]) for i in range(0, len(data), 24)]
    up = name.upper()
    return (f"constexpr int {up}_W = {w}, {up}_H = {h};\n"
            f"static const uint8_t {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n")


mark = Image.open(os.path.join(BRAND, "png", "lapdog-mark-512.png")).convert("RGBA")
k = mark.width / MARK_W
dog = mark.crop((0, 0, round((ARCS_FROM - MARK_X) * k), mark.height))
dog = resize(dog, (round(dog.width / k * SCALE), round(MARK_H * SCALE)))

lockup = Image.open(os.path.join(BRAND, "png", "lapdog-lockup-1200.png")).convert("RGBA")
k = lockup.width / LOCKUP_W
top = (LOCKUP_H - WORD_CAP) / 2
word = lockup.crop((round(WORD_X * k), round(top * k), lockup.width, round((top + WORD_CAP) * k)))
word = resize(word, (round(word.width * WORD_H / word.height), WORD_H))

small = resize(lockup, (round(lockup.width * LOCKUP_PX / lockup.height), LOCKUP_PX))

with open(OUT, "w") as f:
    f.write("#pragma once\n"
            "// LapDog artwork for the touch timer, LVGL RGB565A8 (RGB565 plane, then alpha).\n"
            "// Generated by tools/gen-touch-art.py from lapdog-web's brand kit - don't edit.\n\n"
            "#include <stdint.h>\n\nnamespace touch_art\n{\n\n"
            "// Splash mark: design units to pixels, and the mark's origin (design units)\n"
            "// at the dog bitmap's top-left.\n"
            f"constexpr float SCALE = {SCALE}f;\n"
            f"constexpr float ORIGIN_X = {MARK_X}, ORIGIN_Y = {MARK_Y};\n\n"
            + image("dog", dog) + "\n" + image("wordmark", word) + "\n" + image("lockup", small)
            + "\n} // namespace touch_art\n")
print(f"dog {dog.size}, wordmark {word.size}, lockup {small.size} -> {os.path.normpath(OUT)}")
